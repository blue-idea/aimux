/*
# Create workspace_settings table (per-device cloud storage)

Plain-English summary
- Stores each browser's aimux settings (language, theme, window size, blur, opacity, shortcuts, panel and dock preferences) so they can follow the user across reloads and devices that know the device key.

1. New Tables
- `workspace_settings`
  - `device_id` (text, primary key): random identifier generated by the app and kept in the browser.
  - `settings` (jsonb): the full settings document.
  - `updated_at` (timestamptz): when the row was last saved.

2. Security
- Row level security is enabled.
- Access is limited to rows whose `device_id` matches the `x-device-id` request header sent by the app. Rows from other devices are invisible and cannot be written.
- Only SELECT, INSERT and UPDATE are granted to `anon` and `authenticated`. Deleting rows is not exposed.

3. Notes
- No sign-in is involved. The device key is effectively a secret held by the browser; keep it random and private.
*/

CREATE TABLE IF NOT EXISTS workspace_settings (
  device_id text PRIMARY KEY CHECK (char_length(device_id) BETWEEN 16 AND 128),
  settings jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE workspace_settings ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE ON workspace_settings TO anon, authenticated;

DROP POLICY IF EXISTS "select_own_device_settings" ON workspace_settings;
CREATE POLICY "select_own_device_settings" ON workspace_settings FOR SELECT
  TO anon, authenticated
  USING (device_id = (current_setting('request.headers', true)::json ->> 'x-device-id'));

DROP POLICY IF EXISTS "insert_own_device_settings" ON workspace_settings;
CREATE POLICY "insert_own_device_settings" ON workspace_settings FOR INSERT
  TO anon, authenticated
  WITH CHECK (device_id = (current_setting('request.headers', true)::json ->> 'x-device-id'));

DROP POLICY IF EXISTS "update_own_device_settings" ON workspace_settings;
CREATE POLICY "update_own_device_settings" ON workspace_settings FOR UPDATE
  TO anon, authenticated
  USING (device_id = (current_setting('request.headers', true)::json ->> 'x-device-id'))
  WITH CHECK (device_id = (current_setting('request.headers', true)::json ->> 'x-device-id'));
